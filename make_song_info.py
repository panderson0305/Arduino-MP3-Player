
#!/usr/bin/env python3
"""Generate a compact title-only song_info.h for the Arduino Nano Every."""

from pathlib import Path
import sys
import unicodedata

DEFAULT_INPUT = Path(
    r"C:\Users\Paul Anderson\Desktop\MP3\MP3_Player\songs.txt"
)

INPUT = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
OUTPUT = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_INPUT.parent / "song_info.h"

TITLE_MAX = 42

TRANSLATE = str.maketrans({
    "Ø": "O", "ø": "o", "Đ": "D", "đ": "d",
    "Ł": "L", "ł": "l", "Æ": "AE", "æ": "ae",
    "Œ": "OE", "œ": "oe", "Þ": "Th", "þ": "th",
    "ß": "ss", "ı": "i", "Ŧ": "T", "ŧ": "t",
    "ð": "d", "Ð": "D",
})


def display_ascii(value: str, limit: int) -> str:
    value = value.translate(TRANSLATE)
    value = unicodedata.normalize("NFKD", value)
    value = "".join(ch for ch in value if not unicodedata.combining(ch))
    value = value.encode("ascii", "ignore").decode("ascii")
    value = " ".join(value.split())
    return value[:limit].rstrip()


def c_escape(value: str) -> str:
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def pool_literal(name: str, values: list[str], chunk_size: int = 16) -> str:
    escaped = [c_escape(value) + r"\0" for value in values]
    lines = []

    for i in range(0, len(escaped), chunk_size):
        lines.append(
            '  "' + '"\n  "'.join(escaped[i:i + chunk_size]) + '"'
        )

    return (
        f"const char {name}[] PROGMEM =\n"
        + "\n".join(lines)
        + ";\n"
    )


def main() -> None:
    if not INPUT.exists():
        raise SystemExit(
            f"Could not find {INPUT}. Pass the path to songs.txt."
        )

    records = []

    for line_no, raw in enumerate(
        INPUT.read_text(encoding="utf-8-sig").splitlines(), 1
    ):
        if not raw.strip():
            continue

        fields = raw.split("|")

        if len(fields) != 5:
            raise SystemExit(
                f"Line {line_no}: expected 5 fields, got {len(fields)}"
            )

        try:
            track = int(fields[0].strip())
        except ValueError:
            raise SystemExit(
                f"Line {line_no}: invalid track number {fields[0]!r}"
            )

        title = display_ascii(fields[2], TITLE_MAX) or f"Track {track}"
        records.append((track, title))

    if not records:
        raise SystemExit("No song records found.")

    actual = [track for track, _ in records]
    expected = list(range(1, len(records) + 1))

    if actual != expected:
        raise SystemExit(
            "Track numbers must be consecutive and in playback order "
            "starting at 1."
        )

    offsets = []
    total_bytes = 0

    for _, title in records:
        offsets.append(total_bytes)
        total_bytes += len(title.encode("ascii")) + 1

    if total_bytes > 65535:
        raise SystemExit("Title pool exceeds the 16-bit offset limit.")

    out = [
        "// Auto-generated by make_song_info.py. Do not edit by hand.",
        f"// Source: {INPUT.name}; tracks: {len(records)}; titles only.",
        "#ifndef SONG_INFO_H",
        "#define SONG_INFO_H",
        "",
        "#include <Arduino.h>",
        "#include <avr/pgmspace.h>",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        f"#define SONG_INFO_COUNT {len(records)}",
        "#define SONG_TITLE_BUFFER_SIZE 43",
        "",
    ]

    out.append(pool_literal("songTitlePool", [title for _, title in records]))
    out.append("")
    out.append("const uint16_t songTitleOffsets[] PROGMEM = {")

    for i in range(0, len(offsets), 12):
        out.append("  " + ", ".join(map(str, offsets[i:i + 12])) + ",")

    out += [
        "};",
        "",
        "inline bool getSongTitle(uint16_t trackNumber, char* title, size_t titleSize) {",
        "  if (trackNumber < 1 || trackNumber > SONG_INFO_COUNT ||",
        "      title == nullptr || titleSize == 0) return false;",
        "",
        "  const uint16_t offset = pgm_read_word(&songTitleOffsets[trackNumber - 1]);",
        "  strncpy_P(title, songTitlePool + offset, titleSize - 1);",
        "  title[titleSize - 1] = '\\0';",
        "  return true;",
        "}",
        "",
        "#endif // SONG_INFO_H",
        "",
    ]

    OUTPUT.write_text("\n".join(out), encoding="ascii")

    print(f"Generated: {OUTPUT}")
    print(f"Tracks: {len(records)}")
    print(f"Title string data: {total_bytes:,} bytes")
    print(f"Title offsets: {len(records) * 2:,} bytes")


if __name__ == "__main__":
    main()
